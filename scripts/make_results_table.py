from __future__ import annotations

import json
from pathlib import Path

from docintel.config.loader import find_repo_root

ROOT = Path(__file__).resolve().parents[1]
COLS = ("hit@5", "r@5", "r@10", "p@5", "ndcg@10", "mrr")


def main() -> int:
    root = find_repo_root(ROOT)
    results = root / "results"
    rows: list[dict[str, object]] = []
    if results.is_dir():
        for path in sorted(results.glob("*/retrieval_metrics.json")):
            payload = json.loads(path.read_text(encoding="utf-8"))
            overall = payload.get("overall") or {}
            rows.append(
                {
                    "profile": payload.get("profile"),
                    "split": payload.get("split"),
                    "n": int(overall.get("n") or payload.get("n") or 0),
                    "config_hash": str(payload.get("config_hash") or "")[:12],
                    "index_sig": str(payload.get("index_sig") or "")[:12],
                    "git_sha": str(payload.get("git_sha") or "")[:8],
                    **{k: overall.get(k) for k in COLS},
                    "path": str(path.relative_to(root)),
                }
            )
    out = root / "results" / "README.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Retrieval L1",
        "",
        "Generated by `scripts/make_results_table.py`. `per_question.jsonl` is gitignored.",
        "",
        "| profile | split | n | hit@5 | r@5 | r@10 | p@5 | ndcg@10 | mrr | hashes |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    if not rows:
        lines.append("| _none yet_ |  |  |  |  |  |  |  |  |  |")
        lines.append("")
        lines.append("Windows, after the nomic index exists:")
        lines.append("")
        lines.append("```")
        cmd = "uv run python scripts/run_retrieval_eval.py --split dev --profile"
        lines.append(f"{cmd} exp_dense_only")
        lines.append(f"{cmd} exp_sparse_only")
        lines.append(f"{cmd} exp_hybrid_rrf")
        lines.append(f"{cmd} exp_hybrid_rerank_mxbai")
        lines.append(f"{cmd} exp_hybrid_rerank_mxbai_short")
        lines.append(f"{cmd} exp_hybrid_rerank_bge")
        lines.append("uv run python scripts/make_results_table.py")
        lines.append("```")
    else:
        for row in rows:
            hashes = f"{row['config_hash']} / {row['index_sig']} / {row['git_sha']}"
            cells = [
                str(row["profile"]),
                str(row["split"]),
                str(row["n"]),
                *[_fmt(row.get(k)) for k in COLS],
                hashes,
            ]
            lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(out)
    return 0


def _fmt(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, float):
        return f"{value:.3f}"
    return str(value)


if __name__ == "__main__":
    raise SystemExit(main())
